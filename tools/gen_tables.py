"""Generate helper/tables.h (all patch bytes) from the tested Python modules.

The C++ helper never assembles machine code itself; every byte it writes comes
from here, so it cannot drift from the Python reference and its tests.
Run after changing anything in swtfu/:  python tools/gen_tables.py
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from swtfu.tfu1 import controller, movie_messages, renderer_reset, subtitle_pause, windowed_playback as playback
from swtfu.tfu1.fps import profile, update_rate
from swtfu.tfu1 import game as tfu1_game
from swtfu.tfu2 import game as tfu2_game
from swtfu.tfu2.fps import profile as tfu2_profile
from swtfu.tfu2 import movie_messages as tfu2_movie


def b(data):
    return "B(\"" + "".join(f"\\x{x:02x}" for x in data) + "\")"


out = ["// Generated by tools/gen_tables.py from swtfu/*.py. Do not edit.", "#pragma once", "#include \"game.h\"", ""]

for var, module in (("kTfu1Game", tfu1_game), ("kTfu2Game", tfu2_game)):
    name = module.__name__.split(".")[1]
    out.append(f'static const GameInfo {var} = {{"{name}", L"{module.EXE}", "{module.EXPECTED_HASH}", {b(module.CODE_SIGNATURE)}, 0x{module.APP_GLOBAL:X}}};')
out.append("")

site_names = {
    "physics_smoothing": ("timescale_smoothing", "physics_smoothing"),
    "camera_smoothing": ("camera_eye_xz", "camera_eye_y", "camera_target_xz", "camera_target_y"),
    "input_timing": ("mouse_horizontal_timing", "mouse_vertical_timing", "angular_yaw_smoothing", "angular_pitch_smoothing"),
    "update_rate": tuple(site[2] for site in update_rate.SITES),
}
for game, fps, var in (("tfu1", profile, "kTfu1Fps"), ("tfu2", tfu2_profile, "kTfu2Fps")):
    out.append(f"static const FixedPatch k_{game}_fps_patches[] = {{")
    for name, address, original, patched in fps.PATCHES:
        out.append(f"    {{\"{name}\", 0x{address:X}, {b(original)}, {b(patched)}}},")
    out.append("};")
    groups = []
    for module in fps.HELPERS:
        short = module.__name__.rsplit(".", 1)[1]
        names = getattr(module, "SITE_NAMES", None) or site_names[short]
        assert len(names) == len(module.SITES)
        prefix = f"k_{game}_{short}"
        out.append(f"static const HookSite {prefix}_sites[] = {{")
        for name, site in zip(names, module.SITES):
            out.append(f"    {{\"{name}\", 0x{site[0]:X}, {b(site[1])}}},")
        out.append("};")
        sources = getattr(module, "SOURCES", ())
        out.append(f"static const SourceCheck {prefix}_sources[] = {{")
        for address, original in sources or ((0, b""),):
            out.append(f"    {{0x{address:X}, {b(original)}}},")
        out.append("};")
        out.append(f"static const HookGroup {prefix} = {{\"{short}\", {prefix}_sites, {len(module.SITES)}, "
                   f"{b(module.CODE)}, {getattr(module, 'STRIDE', 64)}, {prefix}_sources, {len(sources)}}};")
        groups.append(f"&{prefix}")
    out.append(f"static const HookGroup* const k_{game}_fps_helpers[] = {{{', '.join(groups) or 'nullptr'}}};")
    out.append(f"static const FpsProfile {var} = {{k_{game}_fps_patches, {len(fps.PATCHES)}, k_{game}_fps_helpers, {len(groups)}, "
               f"0x{fps.LIMIT_OFFSET:X}, 0x{fps.CINEMATIC_STATE:X}, 0x{fps.SAVED_LIMIT_OFFSET:X}}};")
    out.append("")

# TFU2 movie message pump (applied by borderless, not part of the FPS profile).
out.append("static const HookSite k_tfu2_movie_sites[] = {")
for address, original, name in tfu2_movie.SITES:
    out.append(f"    {{\"{name}\", 0x{address:X}, {b(original)}}},")
out += ["};", "static const SourceCheck k_tfu2_movie_sources[] = {{0x0, B(\"\")}};",
        f"static const HookGroup kTfu2MovieMessages = {{\"movie_messages\", k_tfu2_movie_sites, {len(tfu2_movie.SITES)}, "
        f"{b(tfu2_movie.CODE)}, {tfu2_movie.STRIDE}, k_tfu2_movie_sources, 0}};", ""]

out += [f"static const uint32_t kPadSite = 0x{controller.PAD_SITE:X};",
        f"static const Bytes kPadOriginal = {b(controller.PAD_ORIGINAL)};",
        f"static const uint32_t kPadEpilogue = 0x{controller.PAD_EPILOGUE:X};",
        f"static const Bytes kPadHead = {b(bytes.fromhex('538bceffd28b86dc0c0000'))};",
        f"static const uint32_t kSkipSite = 0x{controller.SKIP_SITE:X};",
        f"static const Bytes kSkipOriginal = {b(controller.SKIP_ORIGINAL)};",
        f"static const uint32_t kSkipOffset = {controller.SKIP_OFFSET};",
        f"static const Bytes kSkipCode = {b(controller.skip_code(0))};", ""]
# Self-check: C++ rebuilds pad_code from head + jmp rel32; mirror that here.
assert controller.pad_code(0x10000)[:11] == bytes.fromhex("538bceffd28b86dc0c0000")

out += [f"static const uint32_t kMovieAddress = 0x{movie_messages.ADDRESS:X};",
        f"static const Bytes kMovieOriginal = {b(movie_messages.ORIGINAL)};",
        f"static const Bytes kMovieCode = {b(movie_messages.CODE)};",
        f"static const uint32_t kMovieWaitOffset = {movie_messages.WAIT_OFFSET};",
        "static const uint32_t kMovieWaitSites[] = {" + ", ".join(f"0x{s:X}" for s in movie_messages.WAIT_SITES) + "};",
        f"static const Bytes kMovieWaitOriginal = {b(movie_messages.WAIT_ORIGINAL)};", ""]

out += [f"static const Bytes kSubtitleCode = {b(subtitle_pause.CODE)};",
        "static const SubtitleSite kSubtitleSites[] = {"]
for name, address, original, offset, opcode in subtitle_pause.SITES:
    out.append(f"    {{\"{name}\", 0x{address:X}, {b(original)}, 0x{offset:X}, 0x{opcode:X}}},")
out += ["};", ""]

out.append("static const FixedPatch kPlaybackPatches[] = {")
for name, address, original, patched in playback.PATCHES:
    out.append(f"    {{\"{name}\", 0x{address:X}, {b(original)}, {b(patched)}}},")
out += ["};", "", f"static const FixedPatch kRendererReset = {{\"renderer_reset\", 0x{renderer_reset.ADDRESS:X}, "
        f"{b(renderer_reset.ORIGINAL)}, {b(renderer_reset.PATCHED)}}};", ""]

target = ROOT / "helper" / "tables.h"
target.write_text("\n".join(out), encoding="utf-8")
print(f"wrote {target}")
